def find_graph_node(query: str) -> Optional[Dict[str, Any]]:
    """
    Поиск узла графа по ключевым словам в запросе пользователя.
    Возвращает наиболее релевантный узел графа или None.
    """
    q = query.lower()
    best_node = None
    best_score = 0

    for node_id, node in PROCUREMENT_KNOWLEDGE_GRAPH.items():
        score = 0
        for kw in node.get("keywords", []):
            if kw in q:
                # Точные совпадения важных юридических терминов весят больше
                score += 3 if len(kw.split()) > 1 else 1
        
        # Специальный приоритет для жалобы в ФАС
        if "фас" in q and ("жалоб" in q or "обжалова" in q) and node_id == "fas_complaint_44fz":
            score += 10
        elif "фас" in q and node_id == "fas_complaint_44fz":
            score += 4

        # Специальный приоритет для обжалования / блокировки на Портале поставщиков (Арбитражная комиссия)
        if ("блокировк" in q or "арбитраж" in q or ("жалоб" in q and "фас" not in q)) and node_id == "portal_complaint_arbitration":
            score += 8

        # Приоритет для котировочных сессий
        if "котировочн" in q and node_id == "quotation_session":
            score += 5
        if "ценов" in q and "предложен" in q and node_id == "quotation_session":
            score += 4

        # Приоритет для ЭЦП и КриптоПро
        if ("криптопро" in q or "cryptopro" in q or "плагин" in q) and node_id == "ecp_cryptopro":
            score += 5

        # Приоритет для банковских и независимых гарантий
        if ("гаранти" in q or "обеспечен" in q) and node_id == "bank_guarantee":
            score += 6

        # Разделение: ЕРУЗ / ЕИС vs Регистрация на Портале
        if ("еруз" in q or "аккредитац" in q or "в еис" in q) and node_id == "registration_eruz":
            score += 6
        elif ("регистрац" in q or "зарегистрир" in q) and node_id == "registration_portal":
            score += 5

        # Приоритет для УПД / электронного актирования
        if ("упд" in q or "актирован" in q) and node_id == "contract_execution_upd":
            score += 5

        # Приоритет для ошибки 500 и сбоев Подсистемы
        if ("500" in q or "сбой подсистем" in q or "сбой в работе" in q or "ошибк" in q and "сервер" in q) and node_id == "system_error_troubleshooting":
            score += 8

        # Приоритет для Закупок малого объема (ЗМО) и 223-ФЗ
        if ("малого объем" in q or "змо" in q or "223" in q) and node_id == "zmo_procurement_rules":
            score += 9

        if score > best_score and score >= 2:
            best_score = score
            best_node = node

    return best_node


def format_graph_context_for_llm(node: Dict[str, Any]) -> str:
    """
    Формирует компактный, точный структурированный контекст для LLM (экономия токенов).
    """
    if not node:
        return ""

    lines = [
        f"=== ГРАФОВЫЙ БЛОК ЗНАНИЙ: {node['title']} ===",
        f"Нормативная база: {', '.join(node['law_references'])}",
        f"Способ и канал подачи: {node['channel']}",
        f"Финансовые условия: {node['fee']}",
        "Регламентные сроки:"
    ]
    if "notice" in node:
        lines.append(f"Юридическое разграничение: {node['notice']}")

    for d in node["deadlines"]:
        lines.append(f"  • {d}")

    lines.append("Пошаговый регламент:")
    for s in node["workflow_steps"]:
        lines.append(f"  {s}")

    if "effects" in node:
        lines.append(f"Правовые последствия: {node['effects']}")

    lines.append("==========================================")
    return "\n".join(lines)


def get_workflow_step_response(node_id: str, current_step: int, user_input: str = "") -> Dict[str, Any]:
    """
    Возвращает следующий шаг в пошаговом Workflow-инструкторе.
    """
    node = PROCUREMENT_KNOWLEDGE_GRAPH.get(node_id)
    if not node:
        return {
            "reply": "Данный процесс не найден в базе пошаговых инструкций.",
            "is_finished": True,
            "next_step": current_step
        }

    steps = node.get("workflow_steps", [])
    total_steps = len(steps)

    if current_step >= total_steps:
        return {
            "reply": f"🎉 **Отлично! Все шаги процесса «{node['title']}» успешно пройдены.**\nЕсли у вас есть ещё вопросы или нужно уточнить детали по какому-либо шагу, я готов помочь!",
            "is_finished": True,
            "next_step": total_steps
        }

    step_text = steps[current_step]
    next_step = current_step + 1

    progress = f"(Шаг {next_step} из {total_steps})"
    prompt_to_continue = (
        f"\n\nКогда будете готовы перейти к следующему действию, напишите **«Далее»** или **«Готово»**."
        if next_step < total_steps else
        "\n\nЭто финальный шаг регламента. Напишите **«Завершить»** или задайте уточняющий вопрос."
    )

    reply = f"📋 **{node['title']}** {progress}\n\n{step_text}{prompt_to_continue}"
    return {
        "reply": reply,
        "is_finished": False,
        "next_step": next_step,
        "total_steps": total_steps
    }
