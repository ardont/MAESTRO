"""
Модуль: router.py (ИНТЕЛЛЕКТУАЛЬНЫЙ РОУТЕР И ГАРДРЕЙЛЫ ОБРАЩЕНИЙ)

Назначение:
  Маршрутизация входящих вопросов пользователей по специализированным экспертным линиям поддержки
  Портала Поставщиков Москвы (zakupki.mos.ru) и предварительная фильтрация нежелательного контента.

Какую проблему решает на Портале Поставщиков:
  1. Портал Поставщиков объединяет множество сложных подсистем:
     - Проведение котировочных сессий (подача оферт, снижение цен, победители).
     - Ведение Каталога товаров и модерация СТЕ (КТРУ, характеристики, YML).
     - Электронное актирование и исполнение контрактов (УПД, ЕИС, ошибки РДИК).
     - Технические вопросы настройки рабочего места (КриптоПро CSP, плагины, сертификаты ЭЦП/МЧД).
     - Юридические споры (44-ФЗ, 223-ФЗ, жалобы в ФАС, реестр недобросовестных поставщиков).
  2. Если искать ответ по всей базе данных без разбора, возникает «семантический шум»:
     вопрос про «подписание» может случайно выдать подписание заявки на регистрацию
     вместо подписания проекта контракта в котировочной сессии.
  3. Роутер классифицирует намерение (intent) пользователя и формирует payload-фильтр
     для Qdrant (category_filter), сужая область поиска до нужного раздела базы знаний.
  4. Модуль check_guardrails() мгновенно отсекает ненормативную лексику и провокации.

Выходные данные:
  Словарь маршрутизации с полями:
    - line: Идентификатор линии ("L1".."L8")
    - name: Человекочитаемое название экспертной линии
    - category_filter: Имя категории для фильтрации в векторной базе Qdrant
    - badge_color: Цвет бейджа для пользовательского интерфейса
"""

