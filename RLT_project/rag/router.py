# 1. ГАРДРЕЙЛ: Регулярные выражения для детекции ненормативной лексики
# ─────────────────────────────────────────────
TOXICITY_PATTERNS = [
    r"\b(хуй|ху[яеёи]|пизд|бля[тд]|еба[тьнл]|ёб[а-я]|муда[кч]|говн|сук[аи]|ганд|шлюх|уеб)\b",
    r"\b(нахуй|похуй|заеб|доеб|приеб|выеб|отъеб|разъеб|пидо|ебл)\b"
]
TOXICITY_REGEX = re.compile("|".join(TOXICITY_PATTERNS), re.IGNORECASE)

ERROR_CODE_REGEX = re.compile(r'\b(рдик[_\s]*[a-zA-Z0-9_]+|0x[0-9a-fA-F]{4,8}|н_еис[_\s]*[a-zA-Z0-9_]+)\b', re.IGNORECASE)


def extract_error_code(text: str) -> Optional[str]:
    """Извлекает код технической/интеграционной ошибки (РДИК_1074, 0x80090016 и т.п.)."""
    m = ERROR_CODE_REGEX.search(text)
    return m.group(1).upper() if m else None


def check_guardrails(user_message: str) -> Dict[str, Any]:
    """
    ГАРДРЕЙЛ: мгновенная проверка сообщения пользователя на токсичность и ненормативную лексику.
    """
    if TOXICITY_REGEX.search(user_message):
        return {
            "is_blocked": True,
            "reason": "toxicity",
            "reply": "⚠️ Ваше обращение содержит недопустимую лексику. Пожалуйста, сформулируйте вопрос в корректной форме, соблюдая правила делового общения."
        }
    return {"is_blocked": False}


