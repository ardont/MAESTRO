def route_support_line(user_message: str) -> Dict[str, Any]:
    """
    МАРШРУТИЗАТОР: классифицирует обращение строго по регламенту взаимодействия с пользователем:
      В штатном режиме пользователю отвечает либо 1-я, либо 2-я линия поддержки:
        L1 • Линия общей поддержки и навигации (закупки, ЗМО, КС, регистрация, каталог СТЕ, финансы, законы)
        L2 • Линия технической поддержки (ЭЦП, КриптоПро, МЧД, УПД, ПО, ошибки интерфейса и первичная диагностика)

      Внутренняя 3-я линия (системные инженеры, разработчики, ФАС) задействуется исключительно
      через эскалацию со 2-й линии поддержки при подтверждении инцидента.
    """
    msg_lower = user_message.lower()

    # Проверка на технический код ошибки (РДИК_0161, РДИК_0474, DP_PAKET_EIS, 0x... и т.д.)
    err_code = extract_error_code(user_message)
    if err_code or "рдик" in msg_lower or "интеграционн" in msg_lower or "калуг" in msg_lower or "пакет еис" in msg_lower or "500" in msg_lower:
        res = {
            "line": "L2",
            "name": "Линия технической поддержки (ЭЦП, ПО, УПД)",
            "category_filter": "contract_execution",
            "badge_color": "#0284c7",
            "error_code": err_code or "Технический контроль"
        }
        logger.info(f"[ROUTER] Обращение классифицировано как L2 (диагностика ошибки: {res['error_code']})")
        return res

    scores = {
        "ecp_mchd": sum(1 for kw in KEYWORDS_TECH_ECP if kw in msg_lower),
        "contract_execution": sum(1 for kw in KEYWORDS_CONTRACT if kw in msg_lower),
        "quotation_session": sum(1 for kw in KEYWORDS_QUOTATION if kw in msg_lower),
        "ste_catalog": sum(1 for kw in KEYWORDS_STE if kw in msg_lower),
        "registration": sum(1 for kw in KEYWORDS_REGISTRATION if kw in msg_lower),
        "legal": sum(1 for kw in KEYWORDS_LEGAL if kw in msg_lower),
        "services": sum(1 for kw in KEYWORDS_SERVICES if kw in msg_lower),
    }

    best_cat, best_score = max(scores.items(), key=lambda x: x[1])

    if best_score > 0:
        # L2: Техподдержка: ЭЦП, КриптоПро, МЧД, плагины, электронное актирование/УПД
        if best_cat in ("ecp_mchd", "contract_execution"):
            res = {
                "line": "L2",
                "name": "Линия технической поддержки (ЭЦП, ПО, УПД)",
                "category_filter": best_cat,
                "badge_color": "#0284c7",
                "error_code": None
            }
            logger.info(f"[ROUTER] Вопрос направлен на L2: {best_cat}")
            return res

        # L1: Линия общей поддержки (Закупки, ЗМО, Котировочные сессии, Каталог товаров, Регистрация, Право, Финансы)
        res = {
            "line": "L1",
            "name": "Линия общей поддержки и навигации по Порталу Поставщиков",
            "category_filter": best_cat if best_cat != "legal" else "legislation",
            "badge_color": "#2563eb",
            "error_code": None
        }
        logger.info(f"[ROUTER] Вопрос направлен на L1: {best_cat}")
        return res

    # По умолчанию — Линия общей поддержки (L1)
    res = {
        "line": "L1",
        "name": "Линия общей поддержки и навигации по Порталу Поставщиков",
        "category_filter": None,
        "badge_color": "#2563eb",
        "error_code": None
    }
    logger.info("[ROUTER] Общий вопрос направлен на L1 (без фильтра)")
    return res

