"""
router.py — Интеллектуальный маршрутизатор обращений в поддержку.

Две ключевые функции:

1. check_guardrails() — ГАРДРЕЙЛ (предохранитель)
   Блокирует сообщения с ненормативной лексикой.
   Работает мгновенно (<5мс) через регулярные выражения.

2. route_support_line() — МАРШРУТИЗАТОР
   Определяет линию поддержки:
   - L1 (зелёный) — Общие вопросы (FAQ, навигация по ЛК)
   - L2 (синий)   — Технические (ЭЦП, КриптоПро, плагины)
   - L3 (фиолет.) — Юридические (44-ФЗ, 223-ФЗ, ФАС, споры)
"""

import re
from typing import Dict, Any

# ─────────────────────────────────────────────
# ГАРДРЕЙЛ: Регулярные выражения для детекции мата и агрессии
# ─────────────────────────────────────────────
# \b — граница слова (чтобы не ловить части нормальных слов)
TOXICITY_PATTERNS = [
    r"\b(хуй|ху[яеёи]|пизд|бля[тд]|еба[тьнл]|ёб[а-я]|муда[кч]|говн|сук[аи]|ганд|шлюх|уеб)\b",
    r"\b(нахуй|похуй|заеб|доеб|приеб|выеб|отъеб|разъеб)\b"
]
# Объединяем в один компилированный паттерн (re.IGNORECASE — без учёта регистра)
TOXICITY_REGEX = re.compile("|".join(TOXICITY_PATTERNS), re.IGNORECASE)

# ─────────────────────────────────────────────
# КЛЮЧЕВЫЕ СЛОВА ДЛЯ КЛАССИФИКАЦИИ ЛИНИЙ ПОДДЕРЖКИ
# ─────────────────────────────────────────────

# L2 — Техническая линия: вопросы по ЭЦП, КриптоПро, плагинам, токенам
# Если хоть одно слово из списка встречается в вопросе — маршрутизируем на L2
L2_TECH_KEYWORDS = [
    "криптопро", "cryptopro", "эцп", "плагин", "сертификат", "рутокен", "rutoken",
    "токен", "драйвер", "ошибка плагина", "не подписывает", "браузер", "chromium-gost",
    "яндекс браузер", "кэп", "укэп", "мчд", "джакарта", "jacarta", "считыватель",
    "не удается подписать", "ошибка 0x", "ssl", "tls"
]

# L3 — Юридическая линия: вопросы по законодательству, спорам, ФАС
L3_LEGAL_KEYWORDS = [
    "жалоба в фас", "фас", "рнп", "реестр недобросовестных", "нмцк", "ст 93", "ст 44",
    "статья 93", "статья 44", "отклонили заявку", "отклонение заявки", "протокол разногласий",
    "допсоглашение", "расторжение контракта", "односторонний отказ", "нацрежим",
    "пп 1875", "пп 719", "постановление правительства", "спецсчет", "независимая гарантия",
    "банковская гарантия", "арбитраж", "суд", "44-фз", "223-фз", "615 пп"
]

def check_guardrails(user_message: str) -> Dict[str, Any]:
    """
    ГАРДРЕЙЛ: мгновенная проверка на мат и агрессию.

    Вызывается ПЕРВЫМ — до всех остальных операций.
    Работает <5мс (регулярка, без нейросети).

    Возвращает:
      {"is_blocked": True, "reason": "toxicity", "reply": "..."}  — если мат
      {"is_blocked": False}                                      — если ок
    """
    if TOXICITY_REGEX.search(user_message):
        return {
            "is_blocked": True,
            "reason": "toxicity",
            "reply": "⚠️ Ваше обращение содержит недопустимую лексику. Пожалуйста, переформулируйте ваш вопрос в корректной форме, соблюдая правила делового общения."
        }
    return {"is_blocked": False}


def route_support_line(user_message: str) -> Dict[str, Any]:
    """
    МАРШРУТИЗАТОР: классификация обращения по линиям поддержки.

    Логика:
      1. Считаем кол-во совпадений с L2-ключевыми словами (техника)
      2. Считаем кол-во совпадений с L3-ключевыми словами (юридика)
      3. Кто набрал больше очков — тот и победил
      4. Если никто не набрал — дефолт L1 (общая поддержка)

    Возвращает словарь:
      line            — "L1" / "L2" / "L3"
      name            — человекочитаемое название линии
      category_filter — категория для фильтрации в Qdrant
      badge_color     — цвет бейджа в UI
    """
    msg_lower = user_message.lower()

    # Считаем «очки» для каждой линии (кол-во найденных ключевых слов)
    l2_score = sum(1 for kw in L2_TECH_KEYWORDS if kw in msg_lower)
    l3_score = sum(1 for kw in L3_LEGAL_KEYWORDS if kw in msg_lower)

    # L2: Техническая линия (ЭЦП, КриптоПро, плагины)
    if l2_score > 0 and l2_score >= l3_score:
        return {
            "line": "L2",
            "name": "Линия технической поддержки (ЭЦП, КриптоПро, ПО)",
            "category_filter": "ecp_mchd",   # Фильтруем поиск по категории ЭЦП/МЧД
            "badge_color": "#0284c7"          # Синий
        }
    # L3: Юридическая / экспертная линия (44-ФЗ, 223-ФЗ, ФАС, споры)
    elif l3_score > 0:
        return {
            "line": "L3",
            "name": "Линия экспертной правовой поддержки (44-ФЗ / 223-ФЗ)",
            # Автоматически выбираем нужную подкатегорию:
            "category_filter": "44fz" if "44" in msg_lower else ("223fz" if "223" in msg_lower else "legislation"),
            "badge_color": "#7c3aed"          # Фиолетовый
        }
    # L1: Общая поддержка (ничего специфичного не нашлось)
    else:
        return {
            "line": "L1",
            "name": "Линия общей поддержки и навигации (FAQ / ЛК)",
            "category_filter": None,          # Поиск по всей базе без фильтра
            "badge_color": "#16a34a"          # Зелёный
        }
